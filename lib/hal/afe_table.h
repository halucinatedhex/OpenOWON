static inline const afe_row_t *afe_row(int fn, int range)
{
    if (fn == 8 && range >= AFE_CAP_FIRST && range <= AFE_CAP_LAST)   /* MEAS_CAP */
        return &AFE_CAP[range - AFE_CAP_FIRST];
    if (fn == 8 && (range == 5 || range == 6)) return &AFE_CAP_SLOPE;   /* charge slope */
    if (fn == 6) return &AFE_CONT;                /* MEAS_CONT: one setting */
    if (fn == 7) return &AFE_DIODE;               /* MEAS_DIODE: one setting */
    if (fn == 9) return &AFE_FREQ;                /* MEAS_FREQ: one setting */
    if (fn == 10 && range == 0) return &AFE_TC;   /* MEAS_TEMP, type K */
    if (fn == 10 && range == 1) return &AFE_OHM2[0];   /* PT100: the 500 ohm row, as stock */
    if (fn == 10 && range == 2) return &AFE_OHM2[1];   /* PT1000 (ours, B28): the 5 kohm row */
    if (fn == 1 && range >= 0 && range < 5) return &AFE_ACV[range];   /* MEAS_ACV */
    if (fn == 2 && range >= 0 && range <= AFE_DCI_LAST) return &AFE_DCI[range];   /* MEAS_DCI */
    if (fn == 3 && range >= 0 && range <= AFE_ACI_LAST) return &AFE_ACI[range];   /* MEAS_ACI */
    if (range < 0 || range >= 6) return 0;
    if (fn == 0) return &AFE_DCV[range];          /* MEAS_DCV */
    if (fn == 4) return &AFE_OHM2[range];         /* MEAS_OHM2 */
    return 0;
}

