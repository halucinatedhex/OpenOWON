#!/usr/bin/env python3
"""Turn a .sym file into a GNU ld script of absolute symbols, so extension
code can call stock firmware functions by name."""
import re, sys, pathlib

src = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "symbols/xdm1041_v2.1.2.sym")
dst = pathlib.Path(sys.argv[2] if len(sys.argv) > 2 else "build/stock_symbols.ld")

out, n = ["/* generated by attic/extension/gen-symbols.py - do not edit */"], 0
for line in src.read_text().splitlines():
    line = line.split("#")[0].strip()
    if not line:
        continue
    m = re.match(r"(0x[0-9a-fA-F]+)\s+(\w+)", line)
    if not m:
        print(f"skip: {line}", file=sys.stderr); continue
    addr, name = m.groups()
    out.append(f"PROVIDE({name} = {addr});")
    n += 1
dst.parent.mkdir(exist_ok=True)
dst.write_text("\n".join(out) + "\n")
print(f"{n} symbols -> {dst}")
