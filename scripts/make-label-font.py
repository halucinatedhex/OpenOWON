#!/usr/bin/env python3
"""
Rasterise the label font: Liberation Sans, anti-aliased, into lib/ui/label_font.h.

    scripts/make-label-font.py LiberationSans-Regular.ttf --bold LiberationSans-Bold.ttf

Liberation Sans has Arial's metrics, so the screens match stock's look
(the manual's screens use an Arial-like face, bold for labels). Its
licence is the SIL Open Font License 1.1 (lib/ui/LICENSE-Liberation): a
derived bitmap may be redistributed with the licence, and must not be
called "Liberation" (the Reserved Font Name), so ours is just the label
font. Get the fonts from
https://github.com/liberationfonts/liberation-fonts/releases (2.1.5,
liberation-fonts-ttf-2.1.5.tar.gz).

Four sizes, picked by fb_text's `scale` (lib/ui/ui.c):

    scale 1  small  graph axes, overflow
    scale 2  large  menus, soft-key values, footer values
    scale 3  label  soft-key labels and footer captions (the bold cut)
    scale 4  unit   the unit under the main reading

Each glyph is its ink box, 4 bits of coverage per pixel (two per byte, row
by row), with its advance and its offset from the pen at the baseline.
Characters: printable ASCII and the few symbols a meter needs (° µ Ω ±);
the unit size only what units use. Glyphs are sorted by code point.
Needs Pillow built with FreeType.
"""
import argparse
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
ASCII = [chr(c) for c in range(0x20, 0x7F)]
SYMBOLS = ["°", "µ", "Ω", "±"]
# The unit size only draws unit strings ("mV DC", "kOhm" -> kΩ, "°C", "dBm"):
# capitals, digits and the lower-case letters units use. test_ui checks every
# unit the app can produce against it.
UNIT_CHARS = sorted(set(" %+-./0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabdhkmnpstuz") | set(SYMBOLS))
# Stock's sizes, measured on the manual's screens scaled to 480x320: values
# and labels ~19 px (cap 13.7), the unit ~41 px (docs/ui-development.md).
SIZES = [("small", 1, 14, ASCII + SYMBOLS, False),     # name, fb_text scale, px, characters, bold
         ("large", 2, 19, ASCII + SYMBOLS, False),
         ("label", 3, 19, ASCII + SYMBOLS, True),      # soft-key labels and captions
         ("unit", 4, 41, UNIT_CHARS, False)]


def glyph(font, ch, asc, desc):
    adv = round(font.getlength(ch))
    pad = 4
    w, h = adv + 2 * pad + 8, asc + desc + 2 * pad
    im = Image.new("L", (w, h), 0)
    ImageDraw.Draw(im).text((pad, pad + asc), ch, font=font, anchor="ls", fill=255)
    box = im.getbbox()
    if box is None:                                   # space
        return adv, 0, 0, 0, 0, b""
    x0, y0, x1, y1 = box
    cov = [round(im.getpixel((x, y)) / 17) for y in range(y0, y1) for x in range(x0, x1)]
    if len(cov) % 2:
        cov.append(0)
    packed = bytes(cov[i] << 4 | cov[i + 1] for i in range(0, len(cov), 2))
    return adv, x1 - x0, y1 - y0, x0 - pad, y0 - (pad + asc), packed


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("ttf", help="the regular cut")
    ap.add_argument("--bold", help="the bold cut, for the label size (default: the regular cut)")
    ap.add_argument("-o", "--out", default=str(ROOT / "lib/ui/label_font.h"))
    ap.add_argument("--px", help="pixel sizes small,large,label,unit (default %s)"
                    % ",".join(str(s[2]) for s in SIZES))
    ap.add_argument("--licence", default="lib/ui/LICENSE-Liberation (SIL Open Font License 1.1)",
                    help="licence note for the header comment")
    a = ap.parse_args(argv)
    sizes = SIZES
    if a.px:
        px = [int(v) for v in a.px.split(",")]
        sizes = [(n, sc, p, ch, b) for (n, sc, _, ch, b), p in zip(SIZES, px)]
    src = Path(a.ttf).stem + (f" and {Path(a.bold).stem}" if a.bold else "")

    out = [f"/* Generated by scripts/make-label-font.py from {src}. Do not edit.",
           f" * Font licence: {a.licence}. */",
           "#ifndef LABEL_FONT_H", "#define LABEL_FONT_H", "#include <stdint.h>", "",
           "typedef struct { uint16_t cp; uint8_t adv, w, h; int8_t xo, yo; uint16_t off; } lf_glyph_t;",
           "typedef struct { uint8_t px, cap, asc, desc; uint16_t n; const lf_glyph_t *g; const uint8_t *bits; } lf_font_t;",
           ""]
    total = 0
    for name, scale, px, chars, bold in sizes:
        font = ImageFont.truetype(a.bold if bold and a.bold else a.ttf, px)
        asc, desc = font.getmetrics()
        cap = -font.getbbox("H", anchor="ls")[1]
        rows, bits = [], bytearray()
        for ch in sorted(chars, key=ord):
            adv, w, h, xo, yo, packed = glyph(font, ch, asc, desc)
            if len(bits) + len(packed) > 0xFFFF:
                sys.exit(f"{name}: glyph data over 64 KB")
            rows.append(f"    {{ 0x{ord(ch):04X}, {adv}, {w}, {h}, {xo}, {yo}, {len(bits)} }},  /* {ch!r} */")
            bits += packed
        total += len(bits) + len(rows) * 10
        out.append(f"/* {name}: {px} px, cap height {cap}, used for fb_text scale {scale} */")
        out.append(f"static const uint8_t lf_{name}_bits[{len(bits)}] = {{")
        for i in range(0, len(bits), 16):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in bits[i:i + 16]) + ",")
        out.append("};")
        out.append(f"static const lf_glyph_t lf_{name}_g[{len(rows)}] = {{")
        out += rows
        out.append("};")
        out.append(f"static const lf_font_t lf_{name} = {{ {px}, {cap}, {asc}, {desc}, {len(rows)}, "
                   f"lf_{name}_g, lf_{name}_bits }};")
        out.append("")
    out.append("#endif")
    Path(a.out).write_text("\n".join(out) + "\n")
    print(f"wrote {a.out}: {len(SIZES)} sizes, ~{total} bytes of flash")
    return 0


if __name__ == "__main__":
    sys.exit(main())
