#!/usr/bin/env python3
"""
Emit src/afe_provisional.h: every emulated front-end row, for the panel
build's DIAG:ROW command only (docs/test-plan.md).

    scripts/gen-afe-provisional.py [--json test/data/afe_v2.1.2_emulated.json]

The rows are PROVISIONAL: recovered by emulating v2.1.2 (built for the
older board), not checked on ours. They exist so the bench session can
test a function with DIAG:ROW before it earns a place in
lib/hal/afe_table.h, which holds only rows confirmed on the meter
(CLAUDE.md: "do not emit unverified data" - this header is test input,
never used by the app).

The sequential sweep is used, not --clean: it carries the AD2/RMS enables
(R26 = 0x08, R29 = 0xF8) that stock sets once and the real XDM2041
capture shows (docs/afe-table.md).
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FUNCS = ["DCV", "ACV", "DCI", "ACI", "OHM2", "OHM4", "CONT", "DIODE", "CAP", "FREQ", "TEMP"]


def row(lines):
    burst = None
    pa8 = pa13 = None
    for l in lines:
        if l.startswith("HY 0x00 <- "):
            burst = [int(b, 16) for b in l.split("<- ")[1].split()][32:56]
        elif l.startswith("GPIO "):
            for tok in l.split()[1:]:
                pin, v = tok.split("=")
                if pin == "PA8":
                    pa8 = v == "1"
                if pin == "PA13":
                    pa13 = v == "1"
    if burst is None or len(burst) != 24 or pa8 is None or pa13 is None:
        return None
    if burst[0x37 - 0x20] != 0:
        sys.exit("R37 (test mode) non-zero in an emulated row: refusing")
    return burst, pa8, pa13


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--json", default=str(ROOT / "test/data/afe_v2.1.2_emulated.json"))
    ap.add_argument("-o", "--out", default=str(ROOT / "src/afe_provisional.h"))
    a = ap.parse_args(argv)
    table = json.loads(Path(a.json).read_text())
    out = ["/* Generated by scripts/gen-afe-provisional.py from "
           f"{Path(a.json).name}. Do not edit.",
           " * PROVISIONAL front-end rows (emulated v2.1.2, unchecked on our board),",
           " * for DIAG:ROW on the panel build only. Never used by the app. */",
           "#ifndef AFE_PROVISIONAL_H", "#define AFE_PROVISIONAL_H", "#include <stdbool.h>",
           "#include <stdint.h>", "",
           "typedef struct { uint8_t fn, range; uint8_t r20[24]; bool pa8, pa13; } afe_prov_t;", "",
           "static const afe_prov_t AFE_PROV[] = {"]
    n = 0
    for f, name in enumerate(FUNCS):
        for r in range(7):
            got = row(table.get(f"{name}/{r}", []))
            if not got:
                continue
            b, pa8, pa13 = got
            out.append(f"    {{ {f}, {r}, {{ " + ", ".join(f"0x{x:02x}" for x in b) +
                       f" }}, {'true' if pa8 else 'false'}, {'true' if pa13 else 'false'} }},  /* {name}/{r} */")
            n += 1
    out += ["};", "#define AFE_NPROV (int)(sizeof AFE_PROV / sizeof AFE_PROV[0])", "", "#endif", ""]
    Path(a.out).write_text("\n".join(out))
    print(f"wrote {a.out}: {n} rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
